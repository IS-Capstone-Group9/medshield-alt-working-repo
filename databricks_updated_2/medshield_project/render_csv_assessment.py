"""Generate ordinary Workspace parser code without executing notebook runtime cells."""
import argparse
import ast
from pathlib import Path

PROJECT = Path(__file__).resolve().parent
ALLOWED_IMPORTS = {
    'csv', 'hashlib', 'io', 'json', 're', 'pathlib', 'collections',
    'decimal', 'datetime', 'calendar', 'copy', 'math', 'typing',
}
SOURCES = {'bronze_namespace': '01_sales_bronze.py', 'silver_namespace': '02_sales_silver.py'}


def pure_declarations(filename):
    tree = ast.parse((PROJECT / filename).read_text(encoding='utf-8-sig'))
    functions = [node for node in tree.body if isinstance(node, ast.FunctionDef)]
    needed = {node.id for function in functions for node in ast.walk(function)
              if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load) and node.id.isupper()}
    assignments = []
    imports = []
    for node in tree.body:
        if isinstance(node, ast.Import) and all(alias.name.split('.')[0] in ALLOWED_IMPORTS for alias in node.names):
            imports.append(node)
        elif isinstance(node, ast.ImportFrom) and node.module and node.module.split('.')[0] in ALLOWED_IMPORTS:
            imports.append(node)
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            names = {value.id for value in ast.walk(node)
                     if isinstance(value, ast.Name) and isinstance(value.ctx, ast.Store)}
            if names and all(name.isupper() for name in names):
                assignments.append((names, node))
    selected = []
    while True:
        before = set(needed)
        for names, node in assignments:
            if names & needed:
                needed.update(value.id for value in ast.walk(node)
                              if isinstance(value, ast.Name) and isinstance(value.ctx, ast.Load) and value.id.isupper())
        if needed == before:
            break
    selected.extend(node for names, node in assignments if names & needed)
    for node in selected + functions:
        if any(isinstance(value, ast.Attribute) and value.attr in {'sql', 'table', 'saveAsTable', 'write'}
               for value in ast.walk(node)):
            raise ValueError('Runtime operation in parser declarations: ' + filename)
    return imports + selected + functions


def render():
    pieces = ['"""Pure CSV assessment functions. Generated by render_csv_assessment.py.\n'
              'Upload this as an ordinary Workspace file, preserving the .py filename.\n'
              'No Spark, table access, source writes or notebook execution occurs here.\n"""\n']
    for factory, filename in SOURCES.items():
        source = ast.unparse(ast.Module(body=pure_declarations(filename), type_ignores=[]))
        pieces.append('\ndef ' + factory + '():\n' +
                      '\n'.join('    ' + line if line else '' for line in source.splitlines()) +
                      '\n    return locals()\n')
    return '\n'.join(pieces) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = PROJECT / 'sales_csv_assessment.py'
    expected = render()
    if args.check:
        if not target.is_file() or target.read_text(encoding='utf-8') != expected:
            raise SystemExit('sales_csv_assessment.py differs from reviewed parser declarations.')
    else:
        target.write_text(expected, encoding='utf-8', newline='\n')
    print('Ordinary Workspace parser module ' + ('matches source declarations.' if args.check else 'generated.'))
