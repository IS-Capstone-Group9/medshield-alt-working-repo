"""Builds one reading copy of the paper draft from its parts. Run from repo root:
     python -X utf8 outputs/paper_draft_20261112/build_merged.py [--with-untracked]

The parts stay the source of truth; edit them, not the merged file, then rebuild. Order: Chapter 2 supplement,
Chapter 4 (results), the four-branch and Objective 4 sections, Chapter 5 (limitations), references, appendices.
The four-branch and Objective 4 sections were written in a parallel workstream and both use numbers 4.8 and 4.9, which
clash with Chapter 4 here; they are renumbered 4.10 and 4.11 in the merged copy only. They are included only when they
are committed to git, unless --with-untracked is given, so that work in progress is not published by accident.
Chapters 1 and 3 and the original Chapter 2 live in the group's PDF/Word paper, not in this repository; see
docs/chapters/ for the alignment notes that say what to insert where.
"""
from pathlib import Path
import re, subprocess, sys

D = Path.cwd() / 'outputs/paper_draft_20261112'
read = lambda name: (D / name).read_bytes().decode('utf-8').replace('\r\n', '\n').strip() + '\n'
tracked = lambda name: subprocess.run(['git', 'ls-files', '--error-unmatch', str((D / name).relative_to(Path.cwd()))], capture_output=True).returncode == 0
def section(text, start, end=None):
    i = text.index(start); j = text.index(end, i) if end else len(text); return text[i:j].strip() + '\n'
def renumber(text, old, new):
    """Shift heading numbers (4.9 -> 4.11, 4.9.1 -> 4.11.1) and demote every heading one level, in heading lines only."""
    out = []
    for line in text.split('\n'):
        m = re.match(r'^(#+) (.*)$', line)
        out.append('#' + m.group(1) + ' ' + re.sub(r'^' + re.escape(old) + r'(?=[. ])', new, m.group(2)) if m else line)
    return '\n'.join(out)

ch2, res = read('chapter2_recent_literature.md'), read('results_and_limitations.md')
parts = ['# MedShield DSS: merged paper draft (reading copy)\n',
         '> Built by `build_merged.py` from the files in this folder; do not edit this file directly. It holds the Chapter 2\n'
         '> supplement, Chapter 4, Chapter 5, references and appendices. Chapters 1 and 3 and the original Chapter 2 are in the\n'
         '> group\'s main paper file; `docs/chapters/` says what to insert there. All results are retrospective.\n',
         '# Chapter 2 supplement. Recent literature (2021–2026)\n', section(ch2, '## 2.5 Climate, disease and pharmaceutical demand', '## References'),
         section(res, '# Chapter 4. Results', '# Chapter 5. Limitations')]
pending = []
for name, old, new in (('four_branch_framework.md', '4.8', '4.10'), ('o4_prescriptive_section.md', '4.9', '4.11')):
    if (D / name).exists() and (tracked(name) or '--with-untracked' in sys.argv): parts.append(renumber(read(name), old, new))
    elif (D / name).exists(): pending.append(name)
if pending: parts.append('> **Sections not yet merged:** ' + ', '.join(f'`{p}`' for p in pending) + ' (parallel workstream, not yet committed). Rebuild after they are committed, or run with `--with-untracked`.\n')
parts += [section(res, '# Chapter 5. Limitations'),
          '# References (Chapter 2 supplement)\n', section(ch2, '## References', '## Sections 2.5.5 and 2.5.6').split('\n', 1)[1].strip() + '\n',
          '# Appendix A. Model and formula cross-reference\n', read('model_cross_reference.md').split('\n', 1)[1].strip() + '\n',
          '# Appendix B. Source verification notes\n', section(ch2, '## Sections 2.5.5 and 2.5.6')]
merged = '\n'.join(parts)
# A copy that includes uncommitted sections gets its own name so it is never mistaken for the committed reading copy.
name = 'MedShield_paper_merged_with_pending.md' if '--with-untracked' in sys.argv else 'MedShield_paper_merged.md'
(D / name).write_text(merged, encoding='utf-8', newline='\n')
heads = [l for l in merged.split('\n') if re.match(r'^#{1,2} ', l)]
nums = re.findall(r'^## (\d+\.\d+) ', merged, flags=re.M)
print(f'{name}: {len(merged.split())} words, {len(heads)} top headings; pending: {pending or "none"}; duplicate section numbers: {sorted({n for n in nums if nums.count(n) > 1}) or "none"}')
for h in heads: print('  ', h[:90])
