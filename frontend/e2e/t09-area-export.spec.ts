test.use({ trace: 'off', screenshot: 'off', video: 'off' })
async function csv(page: Page, selector: string) {
  const waiting = page.waitForEvent('download')
  await page.locator(selector).click()
  const text = await readFile((await (await waiting).path())!, 'utf8')
  const lines = text.replace(/^\uFEFF/, '').trim().split(/\r?\n/)
  const parse = (line: string) => [...line.matchAll(/"((?:[^"]|"")*)"(?:,|$)/g)].map(match => match[1].replace(/""/g, '"'))
  const headers = parse(lines.shift()!)
  return { headers, rows: lines.map(line => Object.fromEntries(headers.map((name, index) => [name, parse(line)[index]]))) }
}
test('area raw ranking export follows computed scope/weights and clears on empty/unavailable', async ({ page }) => {
  await page.route('http://medshield.test/**', route => route.fulfill({ contentType: 'text/html', body: '<html><body></body></html>' }))
  await page.goto('http://medshield.test/')
  await page.setContent(`<style>${MEDSHIELD_STYLE}</style>${MEDSHIELD_MARKUP}`)
  await page.evaluate(() => { window.fetch = async () => new Response('{}', { status: 503 }) })
  await page.addScriptTag({ path: path.resolve('node_modules/chart.js/dist/chart.umd.js') })
  await page.evaluate(script => new Function(script)(), getExecutableDashboardScript())
  await page.evaluate(() => {
    const app = window as any
    app.showPage('territory'); app.setDescriptivePeriod('custom'); app.setCustomDateRange('2025-01-01', '2025-12-31')
    const row = (territory: string, region: string, sector: string, revenue: number, period: string, product: string, category = 'Medical') => ({ territory, region, sector, revenue, period, date: period + '-15', product, category, quantity: 1, row_count: 1, evidence: 'actual', basis: 'Synthetic proposed mapping' })
    app.setSalesSectorsData({ rows: [row('Quezon', 'CALABARZON', 'Government', 100.125, '2025-01', 'P1'), row('Quezon', 'CALABARZON', 'Private', 50.25, '2025-02', 'P2'), row('Batangas', 'CALABARZON', 'Government', 75.5, '2025-01', 'P1'), row('Marinduque', 'MIMAROPA', 'Private', 40.125, '2025-02', 'P3', 'Non-Medical'), row('Unassigned geography', null as any, 'Government', 10, '2025-01', 'P1')], source: { file: 'synthetic.Gold', checksum: 'fixture-source-hash', excluded: {}, release: { fact_delta_version: 20, dataset_id: 'fixture-dataset', policy_version: 'fixture-policy', area_mapping_sha256: 'fixture-area', product_master_sha256: 'fixture-product', publication_status: 'CANDIDATE_PENDING_REVIEW' } } })
  })
  expect(await page.evaluate(() => typeof (window as any).exportAreaRankingCSV)).toBe('function')
  await page.selectOption('#sectorEvidence', 'actual')
  await expect(page.locator('#areaRankingExport')).toBeEnabled()
  let result = await csv(page, '#areaRankingExport')
  expect(result.rows).toHaveLength(3)
  const q = result.rows.find(row => row.area === 'Quezon')!
  expect(Number(q.net_sales_php)).toBe(150.375)
  expect(Number(q.historical_sales_score)).toBeCloseTo(60 + 40 * 2 / 12, 12)
  expect(q).toMatchObject({ rank: '1', active_periods: '2', selected_periods: '12', sales_weight_pct: '60', coverage_weight_pct: '40', buyer_filter: 'All', region_filter: 'All', evidence_filter: 'actual', category_filter: 'All', grain: 'month', axis_period_start: '2025-01', axis_period_end: '2025-12', selected_start_date: '2025-01-01', selected_end_date: '2025-12-31', excluded_unmapped_net_sales_php: '10', fact_delta_version: '20', dataset_id: 'fixture-dataset', policy_version: 'fixture-policy', source_checksum: 'fixture-source-hash', publication_status: 'CANDIDATE_PENDING_REVIEW' })
  expect(q.mapping_status).toContain('Proposed')
  expect(q.ranking_scope).toContain('unmapped sales excluded')
  await page.evaluate(() => (window as any).setAreaPriorityWeights(80, 20))
  result = await csv(page, '#areaRankingExport')
  expect(Number(result.rows[0].historical_sales_score)).toBeCloseTo(80 + 20 * 2 / 12, 12)
  expect(result.rows[0].sales_weight_pct).toBe('80')
  await page.selectOption('#sectorRegion', 'CALABARZON')
  await page.selectOption('#sectorCluster', 'Government')
  result = await csv(page, '#areaRankingExport')
  expect(result.rows).toHaveLength(2)
  expect(Number(result.rows.find(row => row.area === 'Quezon')!.net_sales_php)).toBe(100.125)
  expect(result.rows.every(row => row.region_filter === 'CALABARZON' && row.buyer_filter === 'Government')).toBe(true)
  await page.selectOption('#sectorCluster', 'All')
  await page.selectOption('#sectorProduct', 'P2')
  result = await csv(page, '#areaRankingExport')
  expect(result.rows).toHaveLength(1)
  expect(result.rows[0]).toMatchObject({ product_filter: 'P2', area: 'Quezon', net_sales_php: '50.25' })
  await page.selectOption('#sectorProduct', '')
  await page.selectOption('#sectorRegion', 'All')
  await page.selectOption('#sectorCategory', 'Non-Medical')
  result = await csv(page, '#areaRankingExport')
  expect(result.rows[0]).toMatchObject({ area: 'Marinduque', category_filter: 'Non-Medical', net_sales_php: '40.125' })
  await page.selectOption('#sectorCategory', 'All')
  await page.evaluate(() => (window as any).setCustomDateRange('2025-01-15', '2025-02-15'))
  result = await csv(page, '#areaRankingExport')
  expect(result.rows.find(row => row.area === 'Quezon')).toMatchObject({ net_sales_php: '150.375', axis_period_start: '2025-01', axis_period_end: '2025-02', selected_start_date: '2025-01-15', selected_end_date: '2025-02-15', selected_periods: '2' })
  await page.selectOption('#sectorCluster', 'Unknown')
  await expect(page.locator('#areaRankingExport')).toBeDisabled()
  await page.evaluate(() => (window as any).setSalesSectorsData(null, 'Required source failed'))
  await expect(page.locator('#areaRankingExport')).toBeDisabled()
  let downloads = 0
  page.on('download', () => { downloads++ })
  await page.evaluate(() => (window as any).exportAreaRankingCSV())
  await page.waitForTimeout(100)
  expect(downloads).toBe(0)
})

test('reference CSV honors empty/filtered scope and labels draft provenance separately', async ({ page }) => {
  await page.route('http://medshield.test/**', route => route.fulfill({ contentType: 'text/html', body: '<html><body></body></html>' }))
  await page.goto('http://medshield.test/')
  await page.setContent(`<style>${MEDSHIELD_STYLE}</style>${MEDSHIELD_MARKUP}`)
  await page.evaluate(() => { window.fetch = async () => new Response('{}', { status: 503 }) })
  await page.addScriptTag({ path: path.resolve('node_modules/chart.js/dist/chart.umd.js') })
  await page.evaluate(script => new Function(script)(), getExecutableDashboardScript())
  await page.evaluate(() => (window as any).showPage('territory'))
  await page.locator('#areaMappingDetails > summary').click()
  await expect(page.locator('#clientReferenceSection')).toContainText('Bundled draft reference')
  await expect(page.locator('#clientReferenceSection')).not.toContainText('verified client accounts')
  await expect(page.locator('#clientReferenceSection')).not.toContainText('ML model anchors')
  await page.locator('#clientRefSearch').fill('no_such_fixture_account_5a91')
  await expect(page.locator('#clientRefShowingCount')).toHaveText('No accounts matching filter')
  const selector = '#clientReferenceSection button[onclick="exportClientReferenceCSV()"]'
  const empty = await csv(page, selector)
  expect(empty.rows).toEqual([])
  expect(empty.headers).toContain('reference_status')
  await page.locator('#clientRefSearch').fill('CLI-0001')
  const filtered = await csv(page, selector)
  expect(filtered.rows).toHaveLength(1)
  expect(filtered.rows[0]).toMatchObject({ 'Client Code': 'CLI-0001', reference_status: 'Draft reference; review required', reference_source: 'docs/MAPPED_CLIENT_REFERENCE.md' })
  expect(filtered.headers).not.toContain('fact_delta_version')
})
